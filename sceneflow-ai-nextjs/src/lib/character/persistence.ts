import Project from '../../models/Project'
import { sequelize } from '@/config/database'

export type CharacterGender = 'male' | 'female' | 'non-binary' | 'unspecified'
export type GenderSource = 'ai' | 'user'

export interface EnhancedCharacter {
  name: string
  role: string  // protagonist, antagonist, supporting
  
  // Core Identity (3 required fields)
  subject: string            // "Captain Valerius 'Val' Zinn"
  ethnicity: string          // "Mediterranean/Outer Rim Colonies"
  keyFeature: string         // "Scarred, charismatic freelance cargo pilot"
  
  // Appearance Details (5 required fields)
  hairStyle: string          // "Mid-length, swept back, slightly unruly"
  hairColor: string          // "Deep, dark auburn"
  eyeColor: string           // "Bright, electric amber"
  expression: string         // "Constant slight smirk, weary but calculating"
  build: string              // "Wiry, compact, deceptively strong"
  
  // Wardrobe/Attire (for visual consistency across scenes)
  defaultWardrobe?: string           // Primary outfit (e.g., "Navy blue tailored suit, white dress shirt, burgundy silk tie")
  wardrobeAccessories?: string       // Consistent accessories (e.g., "Silver wristwatch, rectangular glasses, gold wedding band")
  
  // Optional fields
  description?: string         // Narrative description
  imagePrompt?: string         // Generated visual prompt
  referenceImage?: string | null  // Vercel Blob URL for both UI display and Imagen API
  referenceImageGCS?: string | null  // DEPRECATED: GCS URL no longer used (kept for backward compatibility)
  appearanceDescription?: string  // AI-generated from reference image for hybrid consistency
  /** Authoritative gender for image/video prompts and voice casting. */
  gender?: CharacterGender
  /** Whether gender was set by the user or inferred/generated by AI. */
  genderSource?: GenderSource
  generating?: boolean
  
  // Metadata
  version: number
  lastModified: string
}

/**
 * Save character attributes to project metadata under a row lock so concurrent
 * saves never clobber `referenceImage`, `wardrobes`, `voiceConfig`, or `script`.
 */
export async function saveCharacterAttributes(
  projectId: string,
  characterName: string,
  attributes: Partial<EnhancedCharacter>
): Promise<void> {
  const cleanAttributes: Record<string, unknown> = {}
  for (const [key, value] of Object.entries(attributes || {})) {
    if (value !== undefined) {
      cleanAttributes[key] = value
    }
  }

  await sequelize.transaction(async (transaction) => {
    const project = await Project.findByPk(projectId, {
      transaction,
      lock: transaction.LOCK.UPDATE,
    })
    if (!project) {
      throw new Error('Project not found')
    }

    const metadata = { ...(project.metadata || {}) }
    const visionPhase = { ...(metadata.visionPhase || {}) }
    const characters = Array.isArray(visionPhase.characters)
      ? [...visionPhase.characters]
      : []

    const attrId = typeof (cleanAttributes as any).id === 'string' ? (cleanAttributes as any).id : ''
    const existingIndex = characters.findIndex((c: any) => {
      if (attrId && c?.id && String(c.id) === attrId) return true
      return c.name?.trim().toLowerCase() === characterName.trim().toLowerCase()
    })

    if (existingIndex >= 0) {
      const existing = characters[existingIndex] || {}
      characters[existingIndex] = {
        ...existing,
        ...cleanAttributes,
        name: existing.name || characterName,
        referenceImage: cleanAttributes.referenceImage ?? existing.referenceImage,
        wardrobes: cleanAttributes.wardrobes ?? existing.wardrobes,
        voiceConfig: cleanAttributes.voiceConfig ?? existing.voiceConfig,
        imageApproved: cleanAttributes.imageApproved ?? existing.imageApproved,
        lastModified: new Date().toISOString(),
        version: (existing.version || 1) + 1,
      }
    } else {
      characters.push({
        ...cleanAttributes,
        name: characterName,
        version: 1,
        lastModified: new Date().toISOString(),
      })
    }

    const newMetadata = {
      ...metadata,
      visionPhase: {
        ...visionPhase,
        characters,
      },
    }

    project.set('metadata', newMetadata)
    project.changed('metadata', true)
    await project.save({ transaction })

    console.log(`[Character Persistence] Saved character: ${characterName}`, {
      totalCharactersNow: characters.length,
      characterFound: true,
      allCharacterNames: characters.map((c: any) => c.name),
    })
  })
}

/**
 * Get character attributes from project metadata
 */
export async function getCharacterAttributes(
  projectId: string,
  characterName: string
): Promise<EnhancedCharacter | null> {
  const project = await Project.findByPk(projectId)
  if (!project) {
    return null
  }

  const metadata = project.metadata || {}
  const visionPhase = metadata.visionPhase || {}
  const characters = visionPhase.characters || []
  
  const character = characters.find(
    (c: any) => c.name?.toLowerCase() === characterName.toLowerCase()
  )
  
  return character || null
}

/**
 * Get all characters for a project
 */
export async function getAllCharacters(
  projectId: string
): Promise<EnhancedCharacter[]> {
  const project = await Project.findByPk(projectId)
  if (!project) {
    return []
  }

  const metadata = project.metadata || {}
  const visionPhase = metadata.visionPhase || {}
  
  return visionPhase.characters || []
}

/**
 * Sync characters from Film Treatment to Vision Phase
 */
export async function syncCharactersFromTreatment(
  projectId: string
): Promise<void> {
  const project = await Project.findByPk(projectId)
  if (!project) {
    throw new Error('Project not found')
  }

  const metadata = project.metadata || {}
  const filmTreatment = metadata.filmTreatmentVariant
  const treatmentCharacters = filmTreatment?.character_descriptions || []
  
  if (treatmentCharacters.length === 0) {
    return
  }
  
  const visionPhase = metadata.visionPhase || {}
  const existingCharacters = visionPhase.characters || []
  
  // Merge treatment characters with existing, preserving any user modifications
  const mergedCharacters = treatmentCharacters.map((tc: any) => {
    const existing = existingCharacters.find(
      (ec: any) => ec.name?.toLowerCase() === tc.name?.toLowerCase()
    )
    
    if (existing) {
      // Preserve user modifications, only update if fields are empty
      return {
        ...tc,
        ...existing,
        // Always update metadata from treatment if not modified by user
        version: existing.version || 1,
        lastModified: existing.lastModified || new Date().toISOString(),
      }
    } else {
      // New character from treatment
      return {
        ...tc,
        version: 1,
        lastModified: new Date().toISOString(),
      }
    }
  })
  
  await project.update({
    metadata: {
      ...metadata,
      visionPhase: {
        ...visionPhase,
        characters: mergedCharacters,
      },
    },
  })
  
  console.log(`[Character Sync] Synced ${mergedCharacters.length} characters from treatment`)
}

