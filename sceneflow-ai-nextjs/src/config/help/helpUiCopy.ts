export function normalizeHelpUiLocale(locale?: string | null): HelpUiLocale {
  const lower = (locale || 'en').trim().toLowerCase()
  if (lower.startsWith('zh')) return 'zh'
  if (lower.startsWith('ja')) return 'ja'
  if (lower.startsWith('ko')) return 'ko'
  if (lower.startsWith('de')) return 'de'
  if (lower.startsWith('fr')) return 'fr'
  if (lower.startsWith('it')) return 'it'
  if (lower.startsWith('nl')) return 'nl'
  if (lower.startsWith('ru')) return 'ru'
  if (lower.startsWith('es')) return 'es'
  if (lower.startsWith('pt')) return 'pt'
  if (lower.startsWith('hi')) return 'hi'
  if (lower.startsWith('ar')) return 'ar'
  if (lower.startsWith('th')) return 'th'
  return 'en'
}

export function getHelpUiCopy(locale?: string | null): HelpUiLocaleCopy {
  const normalized = normalizeHelpUiLocale(locale)
  return HELP_UI_COPY[normalized] ?? HELP_UI_COPY.en
}
